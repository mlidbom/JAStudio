// Makes the MP3 files Mp3LoudnessNormalization's specifications use, and the results mp3gain gives for them, which the specifications compare its with.
//
//    dotnet run dev_scripts/generate-mp3-fixtures.cs -- <mp3gain.exe> <folder with TTS samples>
//
// lame.exe, in the repository's root, encodes generated test signals in the layouts Mp3LoudnessNormalization must read the way mp3gain does:
// MPEG-1, -2 and -2.5, mono and stereo, CBR and VBR, a CRC, ID3v1, ID3v2 and APE tags, and two files joined with a tag between them.
// The file with a CRC has a twin without one, of the same signal, since mp3gain 1.4.6 measures a file with a CRC wrongly and Mp3LoudnessNormalization doesn't.
// Two Azure and two Google TTS files, generated by JAStudio, are copied in as they are: the TTS audio JAStudio normalizes. The folder holding them
// is given as an argument, since they come from the services, not from here: Azure-NanamiNeural-24khz-96kbit.mp3,
// Azure-Nanami-DragonHDLatestNeural-24khz-96kbit.mp3, Google-Chirp3-HD-Kore.mp3 and Google-Chirp3-HD-Gacrux.mp3.
// mp3gain 1.4.6 then measures each (/o /s s), and normalizes a copy (/r /c /s s), into Mp3LoudnessNormalization.Specifications/Mp3Fixtures.
//
// It also makes the fake tts-provider's speech for JAStudio.UI.Specifications: tones encoded as JAStudio's Azure speech is, 24 kHz mono at 96 kbit/s.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;

var mp3Gain = args[0];
var ttsSamples = args[1];
var repository = Path.GetFullPath(Path.Combine(AppContext.GetData("EntryPointFileDirectoryPath") as string ?? Directory.GetCurrentDirectory(), ".."));
var lame = Path.Combine(repository, "lame.exe");
var fixtures = Path.Combine(repository, "src", "src_dotnet", "Mp3LoudnessNormalization.Specifications", "Mp3Fixtures");
var fakeSpeech = Path.Combine(repository, "src", "src_dotnet", "JAStudio.UI.Specifications", "FakeSpeech");
var work = Path.Combine(Path.GetTempPath(), "jastudio-mp3-fixtures");
foreach(var folder in new[] { fixtures, fakeSpeech, work })
{
   if(Directory.Exists(folder)) Directory.Delete(folder, true);
   Directory.CreateDirectory(folder);
}

Encode("lame-vbr-44khz-mono-with-id3-tags", Speech(44100, channels: 1, seconds: 2.0, loudness: 0.6, seed: 1), "-V 4 --add-id3v2 --tt \"JAStudio fixture\" --ta JAStudio");
Encode("lame-cbr-48khz-joint-stereo", Speech(48000, channels: 2, seconds: 2.2, loudness: 0.3, seed: 2), "-b 128 -m j");
Encode("lame-crc-32khz-stereo", Speech(32000, channels: 2, seconds: 1.8, loudness: 0.5, seed: 3), "-b 96 -m s -p");
Encode("lame-32khz-stereo", Speech(32000, channels: 2, seconds: 1.8, loudness: 0.5, seed: 3), "-b 96 -m s");
Encode("lame-24khz-mono", Speech(24000, channels: 1, seconds: 2.0, loudness: 0.7, seed: 4), "-b 96 -m m");
Encode("lame-mpeg-2.5-11khz-mono", Speech(11025, channels: 1, seconds: 2.0, loudness: 0.5, seed: 5), "-b 24 -m m");
Encode("lame-quiet-22khz-mono", Speech(22050, channels: 1, seconds: 2.4, loudness: 0.02, seed: 6), "-b 48 -m m");
var first = EncodeInWork(Speech(44100, channels: 1, seconds: 1.3, loudness: 0.4, seed: 7), "-b 64 -m m --id3v1-only --tt First");
var second = EncodeInWork(Speech(44100, channels: 1, seconds: 1.6, loudness: 0.8, seed: 8), "-b 64 -m m --id3v1-only --tt Second");
File.WriteAllBytes(Path.Combine(fixtures, "two-files-joined-by-a-tag-with-an-ape-tag.mp3"), [..first, ..second[..^128], ..ApeTag(("Title", "Joined")), ..second[^128..]]);
foreach(var (name, sample) in new[]
        {
           ("azure-nanami-24khz", "Azure-NanamiNeural-24khz-96kbit.mp3"),
           ("azure-nanami-dragon-hd-24khz", "Azure-Nanami-DragonHDLatestNeural-24khz-96kbit.mp3"),
           ("google-chirp3-hd-kore-24khz", "Google-Chirp3-HD-Kore.mp3"),
           ("google-chirp3-hd-gacrux-24khz", "Google-Chirp3-HD-Gacrux.mp3"),
        })
   File.Copy(Path.Combine(ttsSamples, sample), Path.Combine(fixtures, name + ".mp3"));

var inputs = Directory.GetFiles(fixtures, "*.mp3").Select(Path.GetFileName).Order(StringComparer.Ordinal).ToArray();
File.WriteAllText(Path.Combine(fixtures, "mp3gain-measurements.tsv"), Run(mp3Gain, fixtures, ["/o", "/s", "s", "/q", ..inputs!]).Replace("\r\n", "\n"));
foreach(var input in inputs) File.Copy(Path.Combine(fixtures, input!), Path.Combine(fixtures, Path.ChangeExtension(input!, ".normalized-by-mp3gain.mp3")));
Run(mp3Gain, fixtures, ["/r", "/c", "/s", "s", "/q", ..inputs.Select(it => Path.ChangeExtension(it!, ".normalized-by-mp3gain.mp3"))]);

File.WriteAllBytes(Path.Combine(fakeSpeech, "steady.mp3"), EncodeInWork(Tone(24000, hertz: 440, seconds: 1.0), "-b 96 -m m"));
foreach(var (number, seconds) in new[] { (1, 1.25), (2, 1.5), (3, 1.75) })
   File.WriteAllBytes(Path.Combine(fakeSpeech, $"varying-{number}.mp3"), EncodeInWork(Tone(24000, hertz: 330, seconds: seconds), "-b 96 -m m"));
Console.WriteLine($"{inputs.Length} fixtures in {fixtures}, and the fake speech in {fakeSpeech}");

void Encode(string name, byte[] wav, string options) => File.WriteAllBytes(Path.Combine(fixtures, name + ".mp3"), EncodeInWork(wav, options));

byte[] EncodeInWork(byte[] wav, string options)
{
   var input = Path.Combine(work, $"{Guid.NewGuid():N}.wav");
   File.WriteAllBytes(input, wav);
   var output = Path.ChangeExtension(input, ".mp3");
   Run(lame, work, ["--quiet", ..SplitOptions(options), Path.GetFileName(input), Path.GetFileName(output)]);
   return File.ReadAllBytes(output);
}

static IEnumerable<string> SplitOptions(string options)
{
   var parts = options.Split('"');
   for(var index = 0; index < parts.Length; index++)
      if(index % 2 == 1) yield return parts[index];
      else foreach(var word in parts[index].Split(' ', StringSplitOptions.RemoveEmptyEntries)) yield return word;
}

static string Run(string program, string folder, IEnumerable<string> arguments)
{
   var start = new ProcessStartInfo(program) { WorkingDirectory = folder, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
   foreach(var argument in arguments) start.ArgumentList.Add(argument);
   using var process = Process.Start(start) ?? throw new InvalidOperationException($"{program} didn't start.");
   var errors = process.StandardError.ReadToEndAsync();
   var output = process.StandardOutput.ReadToEnd();
   process.WaitForExit();
   if(process.ExitCode != 0) throw new InvalidOperationException($"{program} failed with {process.ExitCode}: {errors.Result}");
   return output;
}

// Something like speech, the same every time: syllables of a voice whose pitch wanders, with breath noise, between silences,
// with digital silence at both ends, where encoders give granules a gain of 0. The second channel of stereo is a softer, later copy.
static byte[] Speech(int sampleRate, int channels, double seconds, double loudness, int seed)
{
   var random = new Random(seed);
   var frames = (int)(seconds * sampleRate);
   var silence = (int)(0.2 * sampleRate);
   var samples = new double[frames];
   var syllableStart = silence;
   while(syllableStart < frames - silence)
   {
      var syllableLength = (int)((0.12 + random.NextDouble() * 0.12) * sampleRate);
      var pitch = 110 + random.NextDouble() * 120;
      var strength = 0.4 + random.NextDouble() * 0.6;
      var phase = 0.0;
      for(var index = 0; index < syllableLength && syllableStart + index < frames - silence; index++)
      {
         var progress = (double)index / syllableLength;
         var envelope = Math.Sin(Math.PI * progress) * strength;
         phase += 2 * Math.PI * pitch * (1 + 0.1 * progress) / sampleRate;
         var voice = 0.0;
         for(var harmonic = 1; harmonic * pitch < Math.Min(4000, sampleRate / 2.0); harmonic++) voice += Math.Sin(harmonic * phase) / harmonic;
         samples[syllableStart + index] = envelope * (0.5 * voice + 0.1 * (random.NextDouble() * 2 - 1));
      }
      syllableStart += syllableLength + (int)((0.02 + random.NextDouble() * 0.08) * sampleRate);
   }
   var peak = samples.Max(Math.Abs);
   return Wav(sampleRate, channels, frames, (frame, channel) => channel == 0 ? samples[frame] / peak * loudness : 0.6 * samples[Math.Max(0, frame - 40)] / peak * loudness);
}

static byte[] Tone(int sampleRate, double hertz, double seconds) =>
   Wav(sampleRate, 1, (int)Math.Round(seconds * sampleRate), (frame, _) => 0.5 * Math.Sin(2 * Math.PI * hertz * frame / sampleRate));

static byte[] Wav(int sampleRate, int channels, int frames, Func<int, int, double> sample)
{
   using var stream = new MemoryStream();
   using var writer = new BinaryWriter(stream);
   var dataLength = frames * channels * 2;
   writer.Write("RIFF"u8); writer.Write(36 + dataLength); writer.Write("WAVE"u8);
   writer.Write("fmt "u8); writer.Write(16); writer.Write((short)1); writer.Write((short)channels); writer.Write(sampleRate);
   writer.Write(sampleRate * channels * 2); writer.Write((short)(channels * 2)); writer.Write((short)16);
   writer.Write("data"u8); writer.Write(dataLength);
   for(var frame = 0; frame < frames; frame++)
      for(var channel = 0; channel < channels; channel++)
         writer.Write((short)Math.Clamp(Math.Round(sample(frame, channel) * 32767), short.MinValue, short.MaxValue));
   writer.Flush();
   return stream.ToArray();
}

// An APEv2 tag, with a header and a footer, as mp3gain and other taggers write it.
static byte[] ApeTag(params (string Key, string Value)[] items)
{
   using var itemBytes = new MemoryStream();
   foreach(var (key, value) in items)
   {
      var valueBytes = Encoding.UTF8.GetBytes(value);
      itemBytes.Write(BitConverter.GetBytes(valueBytes.Length));
      itemBytes.Write(BitConverter.GetBytes(0));
      itemBytes.Write(Encoding.ASCII.GetBytes(key));
      itemBytes.WriteByte(0);
      itemBytes.Write(valueBytes);
   }
   byte[] HeaderOrFooter(uint flags) =>
      [.."APETAGEX"u8, ..BitConverter.GetBytes(2000), ..BitConverter.GetBytes((int)itemBytes.Length + 32), ..BitConverter.GetBytes(items.Length), ..BitConverter.GetBytes(flags), ..new byte[8]];
   const uint hasAHeader = 1u << 31;
   const uint isTheHeader = 1u << 29;
   return [..HeaderOrFooter(hasAHeader | isTheHeader), ..itemBytes.ToArray(), ..HeaderOrFooter(hasAHeader)];
}
